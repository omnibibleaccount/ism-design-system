#!/usr/bin/env node
// One icon source, five outputs.
//   Source:  packages/web/assets/ui-icons/source.json   (UI line icons, hand-authored)
//            packages/web/assets/icons/*.svg            (filled ministry icons, from design)
//   Output:  packages/web/assets/ui-icons/<name>.svg
//            packages/tokens/src/icons.generated.ts     (React and React Native: node data, no SVG parsing at runtime)
//            packages/ios/Sources/ISMDesignSystem/Resources/Icons.xcassets/*.imageset + Generated/ISMIcons.swift
//            packages/android/ism-design-system/src/main/res/drawable/ism_ui_*.xml, ism_icon_*.xml + kotlin ISMIcons.kt
// `--check` fails when generated files are stale.
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync, rmSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { ROOT } from './lib/tokens.mjs';

const CHECK = process.argv.includes('--check');
const stale = [];
const files = new Map();
const put = (rel, text) => files.set(rel, text);

const ui = JSON.parse(readFileSync(resolve(ROOT, 'packages/web/assets/ui-icons/source.json'), 'utf8'));
delete ui.$comment;
const uiNames = Object.keys(ui).sort();

const attrsOf = (s) => Object.fromEntries([...s.matchAll(/([a-zA-Z][\w-]*)="([^"]*)"/g)].map((m) => [m[1], m[2]]));
const nodesOf = (inner) => [...inner.matchAll(/<(path|circle|rect)\s+([^>]*?)\/?>/g)].map((m) => [m[1], attrsOf(m[2])]);
const num = (v) => +(+v).toFixed(3);

// ---- UI icon nodes
const uiNodes = Object.fromEntries(uiNames.map((n) => [n, nodesOf(ui[n])]));
for (const n of uiNames) if (!uiNodes[n].length) throw new Error(`UI icon ${n} has no parsable nodes`);

// ---- ministry icons
const minDir = resolve(ROOT, 'packages/web/assets/icons');
const minNames = readdirSync(minDir).filter((f) => f.endsWith('.svg')).map((f) => f.replace(/\.svg$/, '')).sort();
const ministry = Object.fromEntries(minNames.map((n) => {
  const svg = readFileSync(resolve(minDir, `${n}.svg`), 'utf8');
  const viewBox = /viewBox="([^"]+)"/.exec(svg)[1];
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  return [n, { viewBox, paths }];
}));

// ---- logos (single-colour black ink; invert on dark)
const LOGOS = { 'ism-full': 'Full Logo Black.svg', 'ism-mark': 'Logo Black.svg', 'dotbible-full': 'dot.bible Full Logo Black.svg', 'dotbible-icon': 'dot.bible Icon Black.svg' };
const logos = Object.fromEntries(Object.entries(LOGOS).map(([k, f]) => {
  const svg = readFileSync(resolve(ROOT, 'packages/web/assets/logos', f), 'utf8');
  const viewBox = /viewBox="([^"]+)"/.exec(svg)[1];
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  return [k, { viewBox, paths }];
}));
const logoNames = Object.keys(logos);

// ---- web: individual UI svg files
for (const n of uiNames) {
  put(`packages/web/assets/ui-icons/${n}.svg`, `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">${ui[n]}</svg>\n`);
}
put('packages/web/assets/ui-icons/README.md', `# UI line icons\n\nGenerated from \`source.json\` by \`npm run build:icons\`. 24 viewBox, \`stroke="currentColor"\`, stroke-width 1.8, round caps and joins, no fill. Use for buttons, fields, navigation, app bars and list rows. Filled ministry icons are in \`../icons\`.\n\n${uiNames.map((n) => `- \`${n}\``).join('\n')}\n`);

// ---- TypeScript data (React + React Native)
const pascalCase = (s) => s.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
put('packages/tokens/src/icons.generated.ts', `// GENERATED by scripts/build-icons.mjs. Do not edit.
export type IconNode = readonly [tag: 'path' | 'circle' | 'rect', attrs: Readonly<Record<string, string>>];

/** UI line icons: 24 viewBox, stroke currentColor, stroke-width 1.8, round caps and joins, no fill. */
export const uiIcons = ${JSON.stringify(uiNodes, null, 2)} as const satisfies Record<string, readonly IconNode[]>;
export type UiIconName = keyof typeof uiIcons;
export const uiIconNames = ${JSON.stringify(uiNames)} as const;

/** Filled ministry icons: single colour, fill currentColor. Each has its own viewBox. */
export const ministryIcons = ${JSON.stringify(ministry, null, 2)} as const satisfies Record<string, { viewBox: string; paths: readonly string[] }>;
export type MinistryIconName = keyof typeof ministryIcons;
export const ministryIconNames = ${JSON.stringify(minNames)} as const;
`);

put('packages/tokens/src/logos.generated.ts', `// GENERATED by scripts/build-icons.mjs. Do not edit.
/** ISM and dot.Bible logos as path data (black ink). Fill with currentColor or invert on dark backgrounds. */
export const logos = ${JSON.stringify(logos, null, 2)} as const satisfies Record<string, { viewBox: string; paths: readonly string[] }>;
export type LogoName = keyof typeof logos;
export const logoNames = ${JSON.stringify(logoNames)} as const;
`);

// ---- iOS asset catalog + enum
const imageset = (name, svg) => {
  const base = `packages/ios/Sources/ISMDesignSystem/Resources/Icons.xcassets/${name}.imageset`;
  put(`${base}/Contents.json`, JSON.stringify({ images: [{ filename: `${name}.svg`, idiom: 'universal' }], info: { author: 'xcode', version: 1 }, properties: { 'preserves-vector-representation': true, 'template-rendering-intent': 'template' } }, null, 2) + '\n');
  put(`${base}/${name}.svg`, svg);
};
put('packages/ios/Sources/ISMDesignSystem/Resources/Icons.xcassets/Contents.json', JSON.stringify({ info: { author: 'xcode', version: 1 } }, null, 2) + '\n');
for (const n of uiNames) imageset(`ism-ui-${n}`, `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">${ui[n]}</svg>\n`);
for (const n of minNames) imageset(`ism-icon-${n}`, readFileSync(resolve(minDir, `${n}.svg`), 'utf8').replace(/<\?xml[^>]*\?>\s*/, '').replace(/<defs>[\s\S]*?<\/defs>\s*/, '').replace(/ class="cls-1"/g, ''));
for (const n of logoNames) imageset(`ism-logo-${n}`, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${logos[n].viewBox}" fill="#000">${logos[n].paths.map((d) => `<path d="${d}"/>`).join('')}</svg>\n`);
const camelCase = (s) => s.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
put('packages/ios/Sources/ISMDesignSystem/Generated/ISMIcons.swift', `// GENERATED by scripts/build-icons.mjs. Do not edit.
import SwiftUI

/// UI line icons (24pt, template-rendered: tint with .foregroundStyle).
public enum ISMUIIcon: String, CaseIterable, Sendable {
${uiNames.map((n) => `    case ${camelCase(n)} = "ism-ui-${n}"`).join('\n')}

    public var image: Image { Image(rawValue, bundle: .module) }
}

/// Logos (template-rendered black ink; use .foregroundStyle(.white) on dark).
public enum ISMLogo: String, CaseIterable, Sendable {
${logoNames.map((n) => `    case ${camelCase(n)} = "ism-logo-${n}"`).join('\n')}

    public var image: Image { Image(rawValue, bundle: .module) }
}

/// Filled ministry icons (template-rendered). Use at 24, 32 or 48pt.
public enum ISMMinistryIcon: String, CaseIterable, Sendable {
${minNames.map((n) => `    case ${camelCase(n)} = "ism-icon-${n}"`).join('\n')}

    public var image: Image { Image(rawValue, bundle: .module) }
}
`);

// ---- Android vector drawables
const circlePath = (cx, cy, r) => `M${num(cx - r)},${num(cy)}a${r},${r} 0,1,0 ${num(2 * r)},0a${r},${r} 0,1,0 ${num(-2 * r)},0`;
const rectPath = (x, y, w, h, r) => r
  ? `M${num(x + r)},${num(y)}H${num(x + w - r)}A${r},${r} 0 0 1 ${num(x + w)},${num(y + r)}V${num(y + h - r)}A${r},${r} 0 0 1 ${num(x + w - r)},${num(y + h)}H${num(x + r)}A${r},${r} 0 0 1 ${num(x)},${num(y + h - r)}V${num(y + r)}A${r},${r} 0 0 1 ${num(x + r)},${num(y)}Z`
  : `M${x},${y}H${num(x + w)}V${num(y + h)}H${x}Z`;
const nodeToPathData = ([tag, a]) => tag === 'path' ? a.d : tag === 'circle' ? circlePath(+a.cx, +a.cy, +a.r) : rectPath(+a.x, +a.y, +a.width, +a.height, +(a.rx ?? 0));
const snake = (s) => s.replace(/-/g, '_');
const vec = (w, h, vw, vh, paths, stroke) => `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/build-icons.mjs. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${num(w)}dp"
    android:height="${num(h)}dp"
    android:viewportWidth="${vw}"
    android:viewportHeight="${vh}">
${paths.map((d) => stroke
  ? `    <path android:pathData="${d}" android:fillColor="#00000000" android:strokeColor="#FF000000" android:strokeWidth="1.8" android:strokeLineCap="round" android:strokeLineJoin="round" />`
  : `    <path android:pathData="${d}" android:fillColor="#FF000000" />`).join('\n')}
</vector>
`;
const drawable = 'packages/android/ism-design-system/src/main/res/drawable';
for (const n of uiNames) put(`${drawable}/ism_ui_${snake(n)}.xml`, vec(24, 24, 24, 24, uiNodes[n].map(nodeToPathData), true));
for (const n of minNames) {
  const [, , vw, vh] = ministry[n].viewBox.split(/\s+/).map(Number);
  put(`${drawable}/ism_icon_${snake(n)}.xml`, vec(24 * vw / vh, 24, vw, vh, ministry[n].paths, false));
}
for (const n of logoNames) {
  const [, , vw, vh] = logos[n].viewBox.split(/\s+/).map(Number);
  put(`${drawable}/ism_logo_${snake(n)}.xml`, vec(32 * vw / vh, 32, vw, vh, logos[n].paths, false));
}
put('packages/android/ism-design-system/src/main/kotlin/bible/ism/design/icons/ISMIcons.kt', `// GENERATED by scripts/build-icons.mjs. Do not edit.
package bible.ism.design.icons

import androidx.annotation.DrawableRes
import bible.ism.design.R

/** UI line icons (24dp vector drawables, black; tint with Icon(tint = …)). */
enum class ISMUIIcon(@DrawableRes val res: Int) {
${uiNames.map((n) => `    ${pascalCase(n)}(R.drawable.ism_ui_${snake(n)})`).join(',\n')};
}

/** Logos (vector drawables, black ink; tint white on dark). */
enum class ISMLogo(@DrawableRes val res: Int) {
${logoNames.map((n) => `    ${pascalCase(n)}(R.drawable.ism_logo_${snake(n)})`).join(',\n')};
}

/** Filled ministry icons (vector drawables, black; tint with Icon(tint = …)). */
enum class ISMMinistryIcon(@DrawableRes val res: Int) {
${minNames.map((n) => `    ${pascalCase(n)}(R.drawable.ism_icon_${snake(n)})`).join(',\n')};
}
`);

// ---- write / check
for (const [rel, text] of files) {
  const abs = resolve(ROOT, rel);
  if (CHECK) { const cur = existsSync(abs) ? readFileSync(abs, 'utf8') : null; if (cur !== text) stale.push(rel); continue; }
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, text);
}
if (CHECK) { if (stale.length) { console.error(`STALE icons (${stale.length}): ${stale.slice(0, 4).join(', ')}…`); process.exit(1); } console.log('icons: up to date'); }
else console.log(`icons: ${uiNames.length} UI + ${minNames.length} ministry icons + ${logoNames.length} logos -> ${files.size} files`);
