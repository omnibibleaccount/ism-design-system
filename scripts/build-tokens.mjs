#!/usr/bin/env node
// Generates every platform's token files from tokens/tokens.json.
//   CSS            packages/web/css/tokens.css
//   TypeScript     packages/tokens/src/generated.ts, native.generated.ts, tokens.flat.json
//   Swift          packages/ios/Sources/ISMDesignSystem/Generated/ISMTokens.swift
//   Kotlin         packages/android/ism-design-system/src/main/kotlin/bible/ism/design/tokens/ISMTokens.kt
//   Android XML    packages/android/ism-design-system/src/main/res/values/ism_{colors,dimens,integers}.xml
// Usage: node scripts/build-tokens.mjs [--check]   (--check fails if any generated file is out of date)
import { mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import {
  ROOT, loadTokens, flatten, camel, pascal, parseColor, px, ms, em, parseShadow, parseBezier, parseGradient,
} from './lib/tokens.mjs';

const CHECK = process.argv.includes('--check');
const t = loadTokens();
const flat = flatten(t);
const HEADER = 'GENERATED by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand.';
const outputs = new Map();
const out = (rel, text) => outputs.set(rel, text.endsWith('\n') ? text : text + '\n');
const num = (n) => String(+n.toFixed(4));
const ref = (v) => v.replace(/\{([a-z0-9-]+)\}/g, 'var(--$1)');

// ---------------------------------------------------------------- CSS
{
  const lines = [`/* ${HEADER} */`];
  for (const f of t.type.fonts) {
    const file = f.file.replace(/^fonts\//, '../assets/fonts/');
    const fmt = file.endsWith('.ttf') ? 'truetype' : 'opentype';
    lines.push(`@font-face{font-family:"${f.family}";src:url("${file}") format("${fmt}");font-weight:${f.weight};font-style:${f.style};font-display:swap}`);
  }
  const color = flat.filter((x) => x.group === 'color');
  lines.push(':root, [data-theme="light"] {');
  for (const x of color) lines.push(`  --${x.name}: ${ref(x.raw)};`);
  lines.push('}', ':root {');
  for (const x of flat.filter((y) => y.group !== 'color')) lines.push(`  --${x.name}: ${ref(x.raw)};`);
  for (const [k, v] of Object.entries(t.type.families)) lines.push(`  --font-${k}: ${v};`);
  lines.push('  /* per-script line heights (see rules/multilingual-rtl.md) */');
  for (const s of t.script.scripts) {
    lines.push(`  --lh-body-${s.id}: ${s.lineHeightBody};`, `  --lh-heading-${s.id}: ${s.lineHeightHeading};`);
  }
  lines.push('}');
  for (const g of t.type.groups) {
    for (const s of g.styles) {
      const decl = [`font-family:var(--font-${g.family})`, `font-size:${s.fontSize}`, `line-height:${s.lineHeight}`, `font-weight:${s.fontWeight}`];
      if (s.letterSpacing) decl.push(`letter-spacing:${s.letterSpacing}`);
      if (s.fontStyle) decl.push(`font-style:${s.fontStyle}`);
      lines.push(`.${s.name}{${decl.join(';')}}`);
    }
  }
  out('packages/web/css/tokens.css', lines.join('\n'));
}

// ---------------------------------------------------------------- TypeScript (web + shared)
const groupKeys = ['color', 'spacing', 'radius', 'shadow', 'gradient', 'layout', 'tracking', 'blur', 'zIndex', 'duration', 'easing', 'opacity', 'size'];
const tsGroup = (g) => (g === 'breakpoint' ? 'layout' : g);
const typeStyles = t.type.groups.flatMap((g) => g.styles.map((s) => ({ ...s, family: g.family, group: g.name })));
{
  const L = [`// ${HEADER}`, '/* eslint-disable */', ''];
  for (const k of groupKeys) {
    L.push(`export const ${k} = {`);
    for (const x of flat.filter((y) => tsGroup(y.group) === k)) L.push(`  ${JSON.stringify(x.name)}: ${JSON.stringify(x.value)},`);
    L.push('} as const;', `export type ${pascal(k)}Token = keyof typeof ${k};`, '');
  }
  L.push('export const fontFamilies = ' + JSON.stringify(t.type.families, null, 2) + ' as const;', '');
  L.push('export const typography = {');
  for (const s of typeStyles) {
    const o = { fontFamily: s.family, fontSize: s.fontSize, lineHeight: s.lineHeight, fontWeight: s.fontWeight };
    if (s.letterSpacing) o.letterSpacing = s.letterSpacing;
    if (s.fontStyle) o.fontStyle = s.fontStyle;
    L.push(`  ${JSON.stringify(s.name)}: ${JSON.stringify(o)},`);
  }
  L.push('} as const;', 'export type TypographyToken = keyof typeof typography;', '');
  L.push('export const scripts = ' + JSON.stringify(t.script.scripts, null, 2) + ' as const;', '');
  L.push('export const elevationLevels = ' + JSON.stringify(t.elevation.levels, null, 2) + ' as const;', '');
  L.push('export const tokens = { ' + groupKeys.join(', ') + ', fontFamilies, typography, scripts, elevationLevels } as const;', '');
  L.push('/** `var(--name)` for any token name. */', 'export const cssVar = (name: string): string => `var(--${name})`;', '');
  out('packages/tokens/src/generated.ts', L.join('\n'));
  const flatJson = {};
  for (const x of flat) flatJson[x.name] = x.value;
  out('packages/tokens/tokens.flat.json', JSON.stringify(flatJson, null, 2));
}

// ---------------------------------------------------------------- React Native (numbers, not strings)
const ELEVATION = { 'shadow-card-light': 4, 'shadow-lift': 8, 'shadow-overlay': 12, 'shadow-card-dark': 16, 'shadow-focus': 0 };
function gradientPoints(angle) {
  const r = (angle * Math.PI) / 180;
  const sx = Math.sin(r), cy = Math.cos(r);
  return { start: { x: +(0.5 - sx / 2).toFixed(3), y: +(0.5 + cy / 2).toFixed(3) }, end: { x: +(0.5 + sx / 2).toFixed(3), y: +(0.5 - cy / 2).toFixed(3) } };
}
const colorStr = (c) => (c.a === 1 ? '#' + [c.r, c.g, c.b].map((n) => Math.round(n).toString(16).padStart(2, '0')).join('') : `rgba(${c.r},${c.g},${c.b},${num(c.a)})`);
{
  const N = { color: {}, spacing: {}, radius: {}, shadow: {}, gradient: {}, layout: {}, tracking: {}, zIndex: {}, duration: {}, easing: {}, opacity: {}, size: {}, typography: {} };
  for (const x of flat) {
    const g = tsGroup(x.group);
    const c = parseColor(x.value);
    if (g === 'color') N.color[x.name] = colorStr(c);
    else if (g === 'spacing' || g === 'radius' || g === 'layout' || (g === 'size' && px(x.value) !== null)) N[g][x.name] = px(x.value);
    else if (g === 'size') N.size[x.name] = parseFloat(x.value);
    else if (g === 'tracking') N.tracking[x.name] = em(x.value);
    else if (g === 'zIndex') N.zIndex[x.name] = parseInt(x.value, 10);
    else if (g === 'duration') N.duration[x.name] = ms(x.value);
    else if (g === 'easing') N.easing[x.name] = parseBezier(x.value) || x.value;
    else if (g === 'opacity') N.opacity[x.name] = c ? colorStr(c) : parseFloat(x.value);
    else if (g === 'shadow') {
      const s = parseShadow(x.value);
      N.shadow[x.name] = {
        shadowColor: colorStr({ ...s.color, a: 1 }), shadowOffset: { width: s.x, height: s.y }, shadowOpacity: s.color.a,
        shadowRadius: +(s.blur / 2).toFixed(2), elevation: ELEVATION[x.name] ?? 0,
        spread: s.spread, note: 'blur/2 approximates the CSS blur radius on iOS; elevation is the Android approximation.',
      };
    } else if (g === 'gradient') {
      const gr = parseGradient(x.value);
      N.gradient[x.name] = { angle: gr.angle, colors: gr.stops.map((s) => colorStr(s.color)), locations: gr.stops.map((s) => +s.pos.toFixed(3)), ...gradientPoints(gr.angle) };
    }
  }
  const fam = { sans: 'Inter', serif: 'Lora', 'display-alt': 'Neue Power', 'script-accent': 'Miss Noteworthy', 'print-serif': 'Procerus' };
  for (const s of typeStyles) {
    const size = px(s.fontSize);
    const o = { fontFamily: fam[s.family], fontSize: size, lineHeight: +(size * s.lineHeight).toFixed(1), fontWeight: String(s.fontWeight) };
    if (s.letterSpacing) o.letterSpacing = +(em(s.letterSpacing) * size).toFixed(2);
    if (s.fontStyle) o.fontStyle = s.fontStyle;
    N.typography[s.name] = o;
  }
  const L = [`// ${HEADER}`, '/* eslint-disable */', '// React Native values: numbers (dp/pt) and rgba strings. Shadows are RN style objects; gradients are expo-linear-gradient / react-native-linear-gradient props.', ''];
  for (const [k, v] of Object.entries(N)) L.push(`export const ${k} = ${JSON.stringify(v, null, 2)} as const;`, '');
  L.push(`export const nativeTokens = { ${Object.keys(N).join(', ')} } as const;`);
  out('packages/tokens/src/native.generated.ts', L.join('\n'));
}

// ---------------------------------------------------------------- Swift
{
  const f01 = (n) => num(n / 255);
  const sColor = (c) => `Color(.sRGB, red: ${f01(c.r)}, green: ${f01(c.g)}, blue: ${f01(c.b)}, opacity: ${num(c.a)})`;
  const L = [`// ${HEADER}`, 'import SwiftUI', ''];
  L.push('public enum ISMColor {');
  for (const x of flat.filter((y) => y.group === 'color')) L.push(`    /// ${x.usage}`, `    public static let ${camel(x.name)} = ${sColor(parseColor(x.value))}`);
  L.push('}', '');
  const nums = (title, g, conv = (x) => px(x.value), type = 'CGFloat') => {
    L.push(`public enum ${title} {`);
    for (const x of flat.filter((y) => tsGroup(y.group) === g)) { const v = conv(x); if (v !== null && v !== undefined) L.push(`    /// ${x.usage}`, `    public static let ${camel(x.name)}: ${type} = ${num(v)}`); }
    L.push('}', '');
  };
  nums('ISMSpacing', 'spacing'); nums('ISMRadius', 'radius');
  nums('ISMLayout', 'layout');
  nums('ISMSize', 'size', (x) => (px(x.value) ?? parseFloat(x.value)));
  nums('ISMZIndex', 'zIndex', (x) => parseInt(x.value, 10), 'Double');
  L.push('public struct ISMShadowSpec { public let color: Color; public let radius: CGFloat; public let x: CGFloat; public let y: CGFloat }', '');
  L.push('public enum ISMShadow {');
  for (const x of flat.filter((y) => y.group === 'shadow')) {
    const s = parseShadow(x.value);
    L.push(`    /// ${x.usage} CSS: ${x.value}. SwiftUI radius is blur/2; spread is not supported.`, `    public static let ${camel(x.name.replace(/^shadow-/, ''))} = ISMShadowSpec(color: ${sColor(s.color)}, radius: ${num(s.blur / 2)}, x: ${num(s.x)}, y: ${num(s.y)})`);
  }
  L.push('}', '');
  L.push('public enum ISMGradient {');
  for (const x of flat.filter((y) => y.group === 'gradient')) {
    const g = parseGradient(x.value); const p = gradientPoints(g.angle);
    L.push(`    /// ${x.usage}`, `    public static let ${camel(x.name.replace(/^gradient-/, ''))} = LinearGradient(stops: [${g.stops.map((s) => `Gradient.Stop(color: ${sColor(s.color)}, location: ${num(s.pos)})`).join(', ')}], startPoint: UnitPoint(x: ${p.start.x}, y: ${p.start.y}), endPoint: UnitPoint(x: ${p.end.x}, y: ${p.end.y}))`);
  }
  L.push('}', '');
  L.push('public enum ISMMotion {');
  for (const x of flat.filter((y) => y.group === 'duration')) L.push(`    /// ${x.usage}`, `    public static let ${camel(x.name)}: Double = ${num(ms(x.value) / 1000)}`);
  for (const x of flat.filter((y) => y.group === 'easing')) {
    const b = parseBezier(x.value); const name = camel(x.name);
    L.push(`    /// ${x.usage}`, b ? `    public static func ${name}(_ duration: Double) -> Animation { .timingCurve(${b.map(num).join(', ')}, duration: duration) }` : (x.value === 'linear' ? `    public static func ${name}(_ duration: Double) -> Animation { .linear(duration: duration) }` : `    public static func ${name}(_ duration: Double) -> Animation { .easeInOut(duration: duration) }`));
  }
  L.push('}', '');
  L.push('public enum ISMOpacity {');
  for (const x of flat.filter((y) => y.group === 'opacity')) {
    const c = parseColor(x.value);
    L.push(`    /// ${x.usage}`, c ? `    public static let ${camel(x.name)} = ${sColor(c)}` : `    public static let ${camel(x.name)}: Double = ${x.value}`);
  }
  L.push('}', '');
  L.push('public struct ISMTextStyle { public let size: CGFloat; public let lineHeight: Double; public let weight: Font.Weight; public let tracking: Double; public let serif: Bool; public let italic: Bool }', '');
  const wmap = { 300: '.light', 400: '.regular', 500: '.medium', 600: '.semibold', 700: '.bold', 800: '.heavy' };
  L.push('public enum ISMType {');
  for (const s of typeStyles) L.push(`    /// ${s.usage || s.name}`, `    public static let ${camel(s.name)} = ISMTextStyle(size: ${px(s.fontSize)}, lineHeight: ${s.lineHeight}, weight: ${wmap[s.fontWeight]}, tracking: ${s.letterSpacing ? num(em(s.letterSpacing) * px(s.fontSize)) : 0}, serif: ${s.family === 'serif'}, italic: ${s.fontStyle === 'italic'})`);
  L.push('}', '');
  L.push('public struct ISMScript { public let id: String; public let font: String; public let lineHeightBody: Double; public let lineHeightHeading: Double; public let rtl: Bool; public let languages: [String] }', '');
  L.push('public enum ISMScripts {', '    public static let all: [ISMScript] = [');
  for (const s of t.script.scripts) L.push(`        ISMScript(id: "${s.id}", font: "${s.font}", lineHeightBody: ${s.lineHeightBody}, lineHeightHeading: ${s.lineHeightHeading}, rtl: ${s.dir === 'rtl'}, languages: [${s.languages.map((l) => `"${l}"`).join(', ')}]),`);
  L.push('    ]', '}');
  out('packages/ios/Sources/ISMDesignSystem/Generated/ISMTokens.swift', L.join('\n'));
}

// ---------------------------------------------------------------- Kotlin + Android XML
{
  const argb = (c) => '0x' + [Math.round(c.a * 255), Math.round(c.r), Math.round(c.g), Math.round(c.b)].map((n) => n.toString(16).padStart(2, '0')).join('').toUpperCase();
  const kc = (c) => `Color(${argb(c)})`;
  const L = [`// ${HEADER}`, 'package bible.ism.design.tokens', '', 'import androidx.compose.animation.core.CubicBezierEasing', 'import androidx.compose.animation.core.Easing', 'import androidx.compose.animation.core.LinearEasing', 'import androidx.compose.ui.graphics.Color', 'import androidx.compose.ui.text.font.FontWeight', 'import androidx.compose.ui.unit.Dp', 'import androidx.compose.ui.unit.TextUnit', 'import androidx.compose.ui.unit.dp', 'import androidx.compose.ui.unit.em', 'import androidx.compose.ui.unit.sp', ''];
  L.push('object ISMColors {');
  for (const x of flat.filter((y) => y.group === 'color')) L.push(`    /** ${x.usage} */`, `    val ${camel(x.name)} = ${kc(parseColor(x.value))}`);
  L.push('}', '');
  const dps = (title, g, conv = (x) => px(x.value)) => {
    L.push(`object ${title} {`);
    for (const x of flat.filter((y) => tsGroup(y.group) === g)) { const v = conv(x); if (v !== null && v !== undefined && !Number.isNaN(v)) L.push(`    /** ${x.usage} */`, `    val ${camel(x.name)}: Dp = ${num(v)}.dp`); }
    L.push('}', '');
  };
  dps('ISMSpacing', 'spacing'); dps('ISMRadius', 'radius'); dps('ISMLayout', 'layout');
  dps('ISMSize', 'size', (x) => px(x.value));
  L.push('object ISMStrokes {', '    /** UI line icon stroke width (unitless in tokens.json, dp here). */', `    val iconStroke: Dp = ${num(parseFloat(flat.find((x) => x.name === 'icon-stroke').value))}.dp`, '}', '');
  L.push('object ISMZIndex {');
  for (const x of flat.filter((y) => y.group === 'zIndex')) L.push(`    /** ${x.usage} */`, `    const val ${camel(x.name)}: Float = ${parseInt(x.value, 10)}f`);
  L.push('}', '');
  L.push('/** Shadow approximation for Compose. `elevation` drives Modifier.shadow; offset/blur/color are the CSS values for custom drawing. */');
  L.push('data class ISMShadowSpec(val offsetX: Float, val offsetY: Float, val blur: Float, val color: Color, val elevation: Dp)', '');
  L.push('object ISMShadow {');
  for (const x of flat.filter((y) => y.group === 'shadow')) { const s = parseShadow(x.value); L.push(`    /** ${x.usage} CSS: ${x.value} */`, `    val ${camel(x.name.replace(/^shadow-/, ''))} = ISMShadowSpec(${num(s.x)}f, ${num(s.y)}f, ${num(s.blur)}f, ${kc(s.color)}, ${ELEVATION[x.name] ?? 0}.dp)`); }
  L.push('}', '');
  L.push('data class ISMGradientSpec(val angleDegrees: Float, val stops: List<Pair<Float, Color>>)', '');
  L.push('object ISMGradients {');
  for (const x of flat.filter((y) => y.group === 'gradient')) { const g = parseGradient(x.value); L.push(`    /** ${x.usage} */`, `    val ${camel(x.name.replace(/^gradient-/, ''))} = ISMGradientSpec(${num(g.angle)}f, listOf(${g.stops.map((s) => `${num(s.pos)}f to ${kc(s.color)}`).join(', ')}))`); }
  L.push('}', '');
  L.push('object ISMMotion {');
  for (const x of flat.filter((y) => y.group === 'duration')) L.push(`    /** ${x.usage} */`, `    const val ${camel(x.name)}: Int = ${ms(x.value)}`);
  for (const x of flat.filter((y) => y.group === 'easing')) { const b = parseBezier(x.value); L.push(`    /** ${x.usage} */`, `    val ${camel(x.name)}: Easing = ${b ? `CubicBezierEasing(${b.map((n) => num(n) + 'f').join(', ')})` : x.value === 'linear' ? 'LinearEasing' : 'CubicBezierEasing(0.25f, 0.1f, 0.25f, 1f)'}`); }
  L.push('}', '');
  L.push('object ISMOpacity {');
  for (const x of flat.filter((y) => y.group === 'opacity')) { const c = parseColor(x.value); L.push(`    /** ${x.usage} */`, c ? `    val ${camel(x.name)} = ${kc(c)}` : `    const val ${camel(x.name)}: Float = ${x.value}f`); }
  L.push('}', '');
  L.push('/** Typographic role. Resolve `FontFamily` in ISMTheme: serif roles use Lora, everything else Inter. */');
  L.push('data class ISMTextRole(val fontSize: TextUnit, val lineHeight: TextUnit, val fontWeight: FontWeight, val letterSpacing: TextUnit, val serif: Boolean, val italic: Boolean)', '');
  const wk = { 300: 'Light', 400: 'Normal', 500: 'Medium', 600: 'SemiBold', 700: 'Bold', 800: 'ExtraBold' };
  L.push('object ISMType {');
  for (const s of typeStyles) { const sz = px(s.fontSize); L.push(`    /** ${s.usage || s.name} */`, `    val ${camel(s.name)} = ISMTextRole(${sz}.sp, ${num(sz * s.lineHeight)}.sp, FontWeight.${wk[s.fontWeight]}, ${s.letterSpacing ? num(em(s.letterSpacing)) : 0}.em, ${s.family === 'serif'}, ${s.fontStyle === 'italic'})`); }
  L.push('}', '');
  L.push('data class ISMScript(val id: String, val font: String, val lineHeightBody: Float, val lineHeightHeading: Float, val rtl: Boolean, val languages: List<String>)', '');
  L.push('object ISMScripts {', '    val all = listOf(');
  for (const s of t.script.scripts) L.push(`        ISMScript("${s.id}", "${s.font}", ${s.lineHeightBody}f, ${s.lineHeightHeading}f, ${s.dir === 'rtl'}, listOf(${s.languages.map((l) => `"${l}"`).join(', ')})),`);
  L.push('    )', '}');
  out('packages/android/ism-design-system/src/main/kotlin/bible/ism/design/tokens/ISMTokens.kt', L.join('\n'));

  const xc = ['<?xml version="1.0" encoding="utf-8"?>', `<!-- ${HEADER} -->`, '<resources>'];
  for (const x of flat.filter((y) => y.group === 'color')) { const c = parseColor(x.value); xc.push(`    <color name="ism_${x.name.replace(/-/g, '_')}">#${[Math.round(c.a * 255), Math.round(c.r), Math.round(c.g), Math.round(c.b)].map((n) => n.toString(16).padStart(2, '0')).join('').toUpperCase()}</color>`); }
  xc.push('</resources>');
  out('packages/android/ism-design-system/src/main/res/values/ism_colors.xml', xc.join('\n'));
  const xd = ['<?xml version="1.0" encoding="utf-8"?>', `<!-- ${HEADER} -->`, '<resources>'];
  for (const g of ['spacing', 'radius', 'layout', 'size']) for (const x of flat.filter((y) => tsGroup(y.group) === g)) { const v = px(x.value); if (v !== null) xd.push(`    <dimen name="ism_${x.name.replace(/-/g, '_')}">${num(v)}dp</dimen>`); }
  xd.push('</resources>');
  out('packages/android/ism-design-system/src/main/res/values/ism_dimens.xml', xd.join('\n'));
  const xi = ['<?xml version="1.0" encoding="utf-8"?>', `<!-- ${HEADER} -->`, '<resources>'];
  for (const x of flat.filter((y) => y.group === 'duration')) xi.push(`    <integer name="ism_${x.name.replace(/-/g, '_')}">${ms(x.value)}</integer>`);
  for (const x of flat.filter((y) => y.group === 'zIndex')) xi.push(`    <integer name="ism_${x.name.replace(/-/g, '_')}">${parseInt(x.value, 10)}</integer>`);
  xi.push('</resources>');
  out('packages/android/ism-design-system/src/main/res/values/ism_integers.xml', xi.join('\n'));
}

// ---------------------------------------------------------------- write / check
let stale = 0;
for (const [rel, text] of outputs) {
  const abs = resolve(ROOT, rel);
  if (CHECK) {
    if (!existsSync(abs) || readFileSync(abs, 'utf8') !== text) { console.error(`STALE: ${rel}`); stale++; }
  } else {
    mkdirSync(dirname(abs), { recursive: true });
    writeFileSync(abs, text);
  }
}
if (CHECK) {
  if (stale) { console.error(`${stale} generated file(s) are out of date. Run: npm run build:tokens`); process.exit(1); }
  console.log(`tokens: ${outputs.size} generated files are up to date`);
} else {
  console.log(`tokens: wrote ${outputs.size} files from ${flat.length} tokens`);
}
