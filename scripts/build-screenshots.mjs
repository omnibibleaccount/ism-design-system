#!/usr/bin/env node
// Renders every component preview (docs/previews/<Name>.html: components/<Name>/preview.html, else README snippets, styled by packages/web/css)
// to docs/screenshots/<Name>.png. These are the visual reference for people and LLMs: "this is what correct looks like".
//
// Usage:  npm run build:screenshots           render all (needs Chromium; set PLAYWRIGHT_CHROMIUM_PATH or run `npx playwright install chromium`)
//         npm run check:screenshots           fail if any screenshot is out of date (compares content hashes, not pixels)
//         node scripts/build-screenshots.mjs Button Card   render only some components
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';
import { ROOT } from './lib/tokens.mjs';

const check = process.argv.includes('--check');
const only = process.argv.slice(2).filter((a) => !a.startsWith('--'));
const outDir = resolve(ROOT, 'docs/screenshots');
const manifestPath = resolve(outDir, 'manifest.json');
const sha = (s) => createHash('sha256').update(s).digest('hex').slice(0, 16);

const all = JSON.parse(readFileSync(resolve(ROOT, 'specs/all.json'), 'utf8'));
const cssFiles = ['ism.css', 'rtl.css'].map((f) => readFileSync(resolve(ROOT, 'packages/web/css', f), 'utf8')).join('');
const previewBuilder = readFileSync(resolve(ROOT, 'scripts/build-previews.mjs'), 'utf8');
// The React specimens render the current @ism/ui source (bundled by build-previews), so it counts too.
const uiSrc = readdirSync(resolve(ROOT, 'packages/react/src'), { recursive: true }).map(String).filter((f) => /\.tsx?$/.test(f)).sort()
  .map((f) => f + readFileSync(resolve(ROOT, 'packages/react/src', f), 'utf8')).join('');
const cssHash = sha(cssFiles + previewBuilder + uiSrc);
const previewSrc = (n) => { const f = resolve(ROOT, 'components', n, 'preview.html'); return existsSync(f) ? readFileSync(f, 'utf8') : ''; };
const hashes = Object.fromEntries(all.components.map((c) => [c.name, sha(cssHash + JSON.stringify(c.snippets.html) + previewSrc(c.name))]));

if (check) {
  let manifest = {};
  try { manifest = JSON.parse(readFileSync(manifestPath, 'utf8')); } catch { /* none yet */ }
  const stale = all.components.map((c) => c.name).filter((n) => manifest.components?.[n] !== hashes[n] || !existsSync(resolve(outDir, `${n}.png`)));
  if (stale.length) {
    console.error(`STALE screenshots (${stale.length}): ${stale.slice(0, 12).join(', ')}${stale.length > 12 ? ', ...' : ''}\nRun: npm run build:previews && npm run build:screenshots`);
    process.exit(1);
  }
  console.log(`screenshots: ${all.components.length} up to date`);
  process.exit(0);
}

let chromium;
try { ({ chromium } = await import('playwright-core')); } catch { console.error('playwright-core is not installed. Run: npm install'); process.exit(2); }
execFileSync('node', [resolve(ROOT, 'scripts/build-previews.mjs')], { stdio: 'inherit' });
mkdirSync(outDir, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_PATH || undefined });
const page = await browser.newPage({ viewport: { width: 1100, height: 120 } });
const names = only.length ? only : all.components.map((c) => c.name);
const manifest = (() => { try { return JSON.parse(readFileSync(manifestPath, 'utf8')); } catch { return { components: {} }; } })();
for (const name of names) {
  await page.goto(pathToFileURL(resolve(ROOT, 'docs/previews', `${name}.html`)).href);
  await page.evaluate(() => document.fonts.ready);
  await page.addStyleTag({ content: '.pv-nav{display:none}*{animation:none!important;transition:none!important}' });
  await page.waitForTimeout(250);
  await page.screenshot({ path: resolve(outDir, `${name}.png`), fullPage: true });
  manifest.components[name] = hashes[name];
}
await browser.close();
manifest.note = 'Generated by scripts/build-screenshots.mjs. Hashes cover the component snippets plus packages/web/css and packages/react/src; they flag stale images, they are not pixel hashes.';
manifest.components = Object.fromEntries(Object.entries(manifest.components).sort());
writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
writeFileSync(resolve(outDir, 'README.md'), `# Component screenshots

One PNG per component, rendered from the real specimen page (\`components/<Name>/preview.html\`) with the real stylesheet (\`packages/web/css/ism.css\`) and fonts at 1100px width. Treat them as the visual reference for "what correct looks like": layout, spacing, colour, type, states.

- Source of truth for values is still \`tokens/tokens.json\`; for usage rules the component README and \`specs/\`.
- Specimens show the states and variants of each component side by side. Read the label above each variant.
- Regenerate with \`npm run build:screenshots\`. CI fails if they are stale (\`npm run check:screenshots\`).
- Hosted copy: see \`site/\` build (\`npm run build:site\`), published as <base>/screenshots/<Name>.png.

${all.components.map((c) => `- [${c.name}](${c.name}.png) (${c.group})`).join('\n')}
`);
const shots = readdirSync(outDir).filter((f) => f.endsWith('.png')).length;
console.log(`screenshots: wrote ${names.length}, ${shots} PNGs in docs/screenshots`);
