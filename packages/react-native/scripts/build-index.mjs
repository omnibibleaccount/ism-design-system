#!/usr/bin/env node
// Regenerates src/index.ts from src/components/*.tsx.
import { readdirSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const comps = readdirSync(resolve(root, 'src/components')).filter((f) => /^[A-Z].*\.tsx$/.test(f)).map((f) => f.replace(/\.tsx$/, '')).sort();
writeFileSync(resolve(root, 'src/index.ts'), `// GENERATED by scripts/build-index.mjs. Do not edit.
export * from './theme';
export * from './fonts';
export * from './Text';
export * from './Icon';
export * from './a11y';
${comps.map((c) => `export * from './components/${c}';`).join('\n')}
`);
console.log(`react-native: index.ts exports ${comps.length} components`);
