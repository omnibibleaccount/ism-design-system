#!/usr/bin/env node
// Regenerates src/index.ts from src/components/*.tsx so every component is exported by name.
import { readdirSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const comps = readdirSync(resolve(root, 'src/components')).filter((f) => /^[A-Z].*\.tsx$/.test(f)).map((f) => f.replace(/\.tsx$/, '')).sort();
const text = `// GENERATED by scripts/build-index.mjs. Do not edit.
export { cx } from './utils';
export { DirectionProvider, useDirection } from './direction';
export type { Direction } from './direction';
export { UiIcon, MinistryIcon } from './Icon';
export type { UiIconProps, MinistryIconProps } from './Icon';
${comps.map((c) => `export * from './components/${c}';`).join('\n')}
`;
writeFileSync(resolve(root, 'src/index.ts'), text);
console.log(`react: index.ts exports ${comps.length} components`);
