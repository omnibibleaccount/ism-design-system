package bible.ism.design.theme

import androidx.compose.runtime.Immutable
import androidx.compose.runtime.staticCompositionLocalOf
import androidx.compose.ui.graphics.Color
import bible.ism.design.tokens.ISMColors

/**
 * Semantic colour roles resolved for light or dark. Components read these, never raw palette
 * values, so one component works on both. Values come from [ISMColors] (tokens.json) and the
 * dark-surface rules in rules/accessibility.md (for example blue-on-dark for blue text).
 */
@Immutable
class ISMSemanticColors(
    val isDark: Boolean,
    // Surfaces
    val background: Color,
    val surface: Color,
    val surfaceRaised: Color,
    val surfaceMuted: Color,
    val surfaceSelected: Color,
    val hoverFill: Color,
    val pressedFill: Color,
    // Lines
    val border: Color,
    val borderStrong: Color,
    val fieldBorder: Color,
    val fieldBorderHover: Color,
    // Text and icons
    val textPrimary: Color,
    val textSecondary: Color,
    val textBody: Color,
    val textPlaceholder: Color,
    // Action and links
    val action: Color,
    val actionHover: Color,
    val actionPressed: Color,
    val onAction: Color,
    val link: Color,
    val linkHover: Color,
    val linkPressed: Color,
    val focusRing: Color,
    // Tints
    val tintBlue: Color,
    val onTintBlue: Color,
    val tintGold: Color,
    val onTintGold: Color,
    val tintViolet: Color,
    val onTintViolet: Color,
    // Status
    val success: Color,
    val successBg: Color,
    val successLine: Color,
    val error: Color,
    val errorBg: Color,
    val errorLine: Color,
    val errorFieldBg: Color,
    val warning: Color,
    val warningBg: Color,
    val warningLine: Color,
    val info: Color,
    val infoBg: Color,
    val infoLine: Color,
    // Inverse (toast, snackbar) and chips
    val inverseSurface: Color,
    val onInverseSurface: Color,
    val inverseLink: Color,
    val chipSelectedBg: Color,
    val onChipSelected: Color,
    val live: Color,
)

